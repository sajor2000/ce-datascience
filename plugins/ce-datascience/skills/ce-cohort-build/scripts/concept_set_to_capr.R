#!/usr/bin/env Rscript
# Translate a Capr-style concept-set YAML into Capr R code AND ATLAS-compatible JSON.
#
# Why Capr (OHDSI/Capr v2): canonical R API for OHDSI cohort definitions; concept
# sets can be built without a database connection (only OMOP concept_ids needed).
# Renders to the same Circe-be JSON ATLAS produces, so concept sets are portable
# between Capr code and ATLAS UI.
#
# Usage:
#   Rscript concept_set_to_capr.R \
#     --in analysis/cohort/concept-sets/T2DM.yaml \
#     --out-r analysis/cohort/concept-sets/T2DM.R \
#     --out-json analysis/cohort/concept-sets/T2DM.json
#
# Required: install current CRAN packages with install.packages(c("Capr", "yaml"))

for (pkg in c("yaml", "Capr")) {
  if (!requireNamespace(pkg, quietly = TRUE)) {
    cat(sprintf("concept_set_to_capr.R: R package '%s' is not installed; run install.packages('%s') and re-run\n", pkg, pkg),
        file = stderr())
    quit(status = 1)
  }
}
suppressPackageStartupMessages({
  library(yaml)
  library(Capr)
})

parse_args <- function(args) {
  out <- list()
  i <- 1
  while (i <= length(args)) {
    key <- sub("^--", "", args[i])
    out[[key]] <- args[i + 1]
    i <- i + 2
  }
  out
}

`%||%` <- function(x, y) if (is.null(x)) y else x  # base R only gained %||% in 4.4

args <- parse_args(commandArgs(trailingOnly = TRUE))
stopifnot(!is.null(args$`in`), !is.null(args$`out-r`), !is.null(args$`out-json`))

spec   <- yaml::read_yaml(args$`in`)
cs_def <- spec$concept_set
stopifnot(!is.null(cs_def), !is.null(cs_def$primary_concepts), !is.null(cs_def$name))
if (is.null(cs_def$vocabulary_version)) {
  stop("concept set '", cs_def$name, "' has no vocabulary_version; pin it in the YAML before generating code")
}

# Each concept may set include_descendants; a set-level include_descendants is the fallback.
set_desc <- isTRUE(cs_def$include_descendants)
wants_desc <- function(x) if (is.null(x$include_descendants)) set_desc else isTRUE(x$include_descendants)
ids_where <- function(concepts, desc) {
  keep <- Filter(function(x) wants_desc(x) == desc, concepts %||% list())
  vapply(keep, function(x) as.integer(x$concept_id), integer(1))
}

primary_plain <- ids_where(cs_def$primary_concepts, FALSE)
primary_desc  <- ids_where(cs_def$primary_concepts, TRUE)
excl_plain    <- ids_where(cs_def$excluded_concepts, FALSE)
excl_desc     <- ids_where(cs_def$excluded_concepts, TRUE)

# Build cs(<ids>, descendants(<ids>), exclude(<ids>, descendants(<ids>)), name = "...")
# as both a live Capr object and the equivalent R source, so the two cannot drift.
ids_src  <- function(ids) paste(ids, collapse = ", ")
cs_args  <- list()
src_args <- character(0)
if (length(primary_plain) > 0) {
  cs_args  <- c(cs_args, as.list(primary_plain))
  src_args <- c(src_args, ids_src(primary_plain))
}
if (length(primary_desc) > 0) {
  cs_args  <- c(cs_args, list(do.call(Capr::descendants, as.list(primary_desc))))
  src_args <- c(src_args, sprintf("descendants(%s)", ids_src(primary_desc)))
}
excl_args <- list()
excl_src  <- character(0)
if (length(excl_plain) > 0) {
  excl_args <- c(excl_args, as.list(excl_plain))
  excl_src  <- c(excl_src, ids_src(excl_plain))
}
if (length(excl_desc) > 0) {
  excl_args <- c(excl_args, list(do.call(Capr::descendants, as.list(excl_desc))))
  excl_src  <- c(excl_src, sprintf("descendants(%s)", ids_src(excl_desc)))
}
if (length(excl_args) > 0) {
  cs_args  <- c(cs_args, list(do.call(Capr::exclude, excl_args)))
  src_args <- c(src_args, sprintf("exclude(%s)", paste(excl_src, collapse = ", ")))
}
cs_args$name <- cs_def$name
src_args <- c(src_args, sprintf("name = %s", deparse(cs_def$name)))

concept_set <- do.call(Capr::cs, cs_args)

# Write the Capr R code mirror so the YAML stays the source of truth but R can re-derive.
r_code <- c(
  "# Auto-generated from concept-set YAML by concept_set_to_capr.R",
  "# Vocabulary version pinning lives in the YAML; do not edit this file directly.",
  "library(Capr)",
  "",
  sprintf("# %s (%s, vocab %s)", cs_def$name, cs_def$vocabulary %||% "OMOP", cs_def$vocabulary_version),
  "",
  sprintf("%s <- cs(%s)", make.names(cs_def$name), paste(src_args, collapse = ", "))
)
writeLines(r_code, args$`out-r`)

# Write the ATLAS-compatible JSON.
Capr::writeConceptSet(concept_set, args$`out-json`)

cat(sprintf("__CE_COHORT_CAPR__ name=%s n_primary=%d n_primary_with_descendants=%d n_excluded=%d r=%s json=%s\n",
            cs_def$name, length(primary_plain) + length(primary_desc), length(primary_desc),
            length(excl_plain) + length(excl_desc),
            args$`out-r`, args$`out-json`))
